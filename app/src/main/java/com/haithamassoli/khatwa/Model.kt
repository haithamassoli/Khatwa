package com.haithamassoli.khatwa

// Shared contracts. All durations in seconds, distances in meters (PRD §12).
// Changing anything here affects every other file: coordinate before editing.

data class Pt(val lat: Double, val lng: Double)

enum class Objective { MODELED, DRIVE_TIME, DRIVE_DISTANCE }

enum class Verification { VERIFIED, UNVERIFIED, REPORTED }

enum class PointUse { PICKUP, DROPOFF, BOTH }

data class Candidate(
    val id: String,
    val pt: Pt,
    val name: String,
    val roadSide: String = "",   // free text, e.g. "جهة المول"
    val landmark: String = "",
    val use: PointUse = PointUse.BOTH,
    val verification: Verification = Verification.VERIFIED,
    val enabled: Boolean = true,
    val auto: Boolean = false,   // generated by auto-suggest, not saved by the user
    val isDirect: Boolean = false, // the origin/destination itself (baseline point, walk = 0)
)

data class SearchInput(
    val origin: Pt,
    val destination: Pt,
    val maxWalkStartS: Int = 600, // 0..600
    val maxWalkEndS: Int = 600,   // 0..600
    val objective: Objective = Objective.MODELED,
)

data class RouteOption(
    val pickup: Candidate,
    val dropoff: Candidate,
    val walkStartS: Int,
    val driveS: Int,
    val driveM: Int,
    val walkEndS: Int,
) {
    val walkTotalS get() = walkStartS + walkEndS
    val modeledS get() = walkStartS + driveS + walkEndS
}

// One matrix cell as returned by the routing layer; null fields = element failed.
data class Leg(val durationS: Int?, val distanceM: Int?)

data class SearchResult(
    val requestId: Long,
    val input: SearchInput,
    val baseline: RouteOption?,          // direct pickup at origin -> dropoff at destination
    val alternatives: List<RouteOption>, // max 3, never contains the baseline pair
    val warnings: List<String>,          // Arabic, user-facing
    val trafficAware: Boolean,
    val calculatedAtMs: Long,
    val pairsChecked: Int,
    val pairsFailed: Int,
    val elementsUsed: Int,               // billable matrix elements this search
)

// Detailed legs for the option detail screen.
data class OptionDetail(
    val walkStart: List<Pt>,
    val drive: List<Pt>,
    val walkEnd: List<Pt>,
    val walkStartS: Int?, val driveS: Int?, val walkEndS: Int?,
)

data class FareObservation(
    val id: String,
    val atMs: Long,
    val provider: String,            // e.g. Careem, Uber, Jeeny
    val vehicleCategory: String,
    val amount: Double?,             // null = unknown, never 0 (PRD §12)
    val currency: String = "JOD",
    val isBaseline: Boolean,         // quote was for the direct trip or for the alternative
    val pickupName: String,
    val dropoffName: String,
    val actualFare: Double? = null,
    val actualWaitS: Int? = null,
    val note: String = "",
)

data class PlaceHit(val name: String, val address: String, val pt: Pt)

data class Quota(val month: String, val searches: Int, val elements: Int, val maxSearches: Int)
